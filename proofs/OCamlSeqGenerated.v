#[bypass_check(guard)]
Fixpoint filter_map_find_left_map {A B C : Set}
  (f_value : A -> sum B C) (xs : t A) (function_parameter : unit)
  {struct function_parameter} : node B :=
  let '_ := function_parameter in
  match xs tt with
  | Nil => Nil
  | Cons x_value xs =>
    match f_value x_value with
    | inl y_value => Cons y_value (filter_map_find_left_map f_value xs)
    | inr _ => filter_map_find_left_map f_value xs tt
    end
  end.

#[bypass_check(guard)]
Fixpoint filter_map_find_right_map {A B C : Set}
  (f_value : A -> sum B C) (xs : t A) (function_parameter : unit)
  {struct function_parameter} : node C :=
  let '_ := function_parameter in
  match xs tt with
  | Nil => Nil
  | Cons x_value xs =>
    match f_value x_value with
    | inl _ => filter_map_find_right_map f_value xs tt
    | inr z_value => Cons z_value (filter_map_find_right_map f_value xs)
    end
  end.

Definition partition_map {A B C : Set} (f_value : A -> sum B C) (xs : t A)
  : t B * t C :=
  ((filter_map_find_left_map f_value xs), (filter_map_find_right_map f_value xs)).

Definition partition {A : Set} (p_value : A -> bool) (xs : t A) : t A * t A :=
  ((filter p_value xs),
    (filter (fun (x_value : A) => negb (p_value x_value)) xs)).

Definition peel {A : Set} (xss : t (unit -> node A)) : t A * t (t A) :=
  unzip (filter_map uncons xss).

#[local] Instance unreachable_transpose : Unreachable unit.
Admitted.

#[bypass_check(guard)]
Fixpoint transpose {A : Set} (xss : t (t A)) (function_parameter : unit)
  {struct function_parameter} : node (t A) :=
  let '_ := function_parameter in
  let '(heads, tails) := peel xss in
  if is_empty heads then
    let '_ :=
      if is_empty tails then tt else RocqOfOCaml.Basics.unreachable in
    Nil
  else
    Cons heads (transpose tails).

#[bypass_check(guard)]
Fixpoint diagonals_shadow1 {A : Set}
  (remainders : t (t A)) (xss : t (unit -> node A)) (function_parameter : unit)
  {struct function_parameter} : node (t A) :=
  let '_ := function_parameter in
  match xss tt with
  | Cons xs xss =>
    match xs tt with
    | Cons x_value xs =>
      let '(heads, tails) := peel remainders in
      Cons (cons x_value heads) (diagonals_shadow1 (cons xs tails) xss)
    | Nil =>
      let '(heads, tails) := peel remainders in
      Cons heads (diagonals_shadow1 tails xss)
    end
  | Nil => transpose remainders tt
  end.

Definition diagonals {A : Set} (xss : t (unit -> node A)) : t (t A) :=
  diagonals_shadow1 empty xss.

Definition map_product {A B C : Set}
  (f_value : A -> B -> C) (xs : t A) (ys : t B) : unit -> node C :=
  concat
    (diagonals
      (map
        (fun (x_value : A) =>
          map (fun (y_value : B) => f_value x_value y_value) ys) xs)).

Definition product {A B : Set} (xs : t A) (ys : t B) : unit -> node (A * B) :=
  map_product (fun (x_value : A) => fun (y_value : B) => (x_value, y_value)) xs
    ys.

#[bypass_check(guard)]
Definition of_dispenser {A : Set} (it : unit -> option A) : t A :=
  let fix c_value (function_parameter : unit) {struct function_parameter}
    : node A :=
    let '_ := function_parameter in
    match it tt with
    | None => Nil
    | Some x_value => Cons x_value c_value
    end in
  c_value.

Definition to_dispenser {A : Set} (xs : t A) : unit -> option A :=
  let s_value := RocqOfOCaml.Basics.Stdlib.ref_value xs in
  fun (function_parameter : unit) =>
    let '_ := function_parameter in
    match RocqOfOCaml.Basics.Stdlib.op_exclamation s_value tt with
    | Nil => None
    | Cons x_value xs =>
      let '_ := RocqOfOCaml.Basics.Stdlib.op_coloneq s_value xs in
      Some x_value
    end.

