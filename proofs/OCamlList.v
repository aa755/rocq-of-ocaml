#[bypass_check(guard)]
Fixpoint equal {A B : Set} (eq : A -> B -> bool) (l1 : t A) (l2 : t B)
  {struct l1} : bool :=
  match (l1, l2) with
  | ([], []) => true
  | (([], Datatypes.cons _ _) | (Datatypes.cons _ _, [])) => false
  | (Datatypes.cons a1 l1, Datatypes.cons a2 l2) =>
    andb (eq a1 a2) (equal eq l1 l2)
  end.

#[bypass_check(guard)]
Fixpoint compare {A B : Set} (cmp : A -> B -> int) (l1 : t A) (l2 : t B)
  {struct l1} : int :=
  match (l1, l2) with
  | ([], []) => 0
  | ([], Datatypes.cons _ _) => (-1)
  | (Datatypes.cons _ _, []) => 1
  | (Datatypes.cons a1 l1, Datatypes.cons a2 l2) =>
    let c_value := cmp a1 a2 in
    if nequiv_decb c_value 0 then
      c_value
    else
      compare cmp l1 l2
  end.

