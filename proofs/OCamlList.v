  end.

#[bypass_check(guard)]
Definition fold_left_map {A B C : Set}
  (f_value : A -> B -> A * C) (accu : A) (l_value : t B) : A * t C :=
  let fix aux (accu : A) (l_accu : t C) (function_parameter : t B)
    {struct l_accu} : A * t C :=
    match function_parameter with
    | [] => (accu, (rev l_accu))
    | Datatypes.cons x_value l_value =>
      let '(accu, x_value) := f_value accu x_value in
      aux accu (Datatypes.cons x_value l_accu) l_value
    end in
  aux accu nil l_value.

#[bypass_check(guard)]
Definition partition {A : Set} (p_value : A -> bool) (l_value : t A)
  : t A * t A :=
  let fix part (yes : t A) (no : t A) (function_parameter : t A) {struct yes}
    : t A * t A :=
    match function_parameter with
    | [] => ((rev yes), (rev no))
    | Datatypes.cons x_value l_value =>
      if p_value x_value then
        part (Datatypes.cons x_value yes) no l_value
      else
        part yes (Datatypes.cons x_value no) l_value
    end in
  part nil nil l_value.

#[bypass_check(guard)]
Definition partition_map {A B C : Set} (p_value : A -> sum B C) (l_value : t A)
  : t B * t C :=
  let fix part (_left : t B) (_right : t C) (function_parameter : t A)
    {struct _left} : t B * t C :=
    match function_parameter with
    | [] => ((rev _left), (rev _right))
    | Datatypes.cons x_value l_value =>
      match p_value x_value with
      | inl v_value => part (Datatypes.cons v_value _left) _right l_value
      | inr v_value => part _left (Datatypes.cons v_value _right) l_value
      end
    end in
  part nil nil l_value.

#[bypass_check(guard)]
Fixpoint split {A B : Set} (function_parameter : t (A * B))
  {struct function_parameter} : t A * t B :=
  match function_parameter with
  | [] => (nil, nil)
  | Datatypes.cons (x_value, y_value) l_value =>
    let '(rx, ry) := split l_value in
    ((Datatypes.cons x_value rx), (Datatypes.cons y_value ry))
  end.

#[bypass_check(guard)]
Fixpoint combine {A B : Set} (l1 : t A) (l2 : t B) {struct l1} : t (A * B) :=
  match (l1, l2) with
  | ([], []) => nil
  | (Datatypes.cons a1 l1, Datatypes.cons a2 l2) =>
    Datatypes.cons (a1, a2) (combine l1 l2)
  | (_, _) => RocqOfOCaml.Basics.Stdlib.invalid_arg "List.combine"
  end.

#[bypass_check(guard)]
Fixpoint merge {A : Set} (cmp : A -> A -> int) (l1 : t A) (l2 : t A) {struct l1}
  : t A :=
  match (l1, l2) with
  | ([], l2) => l2
  | (l1, []) => l1
  | (Datatypes.cons h1 t1, Datatypes.cons h2 t2) =>
    if RocqOfOCaml.Basics.Stdlib.le (cmp h1 h2) 0 then
      Datatypes.cons h1 (merge cmp t1 l2)
    else
      Datatypes.cons h2 (merge cmp l1 t2)
  end.

#[bypass_check(guard)]
Definition stable_sort {A : Set} (cmp : A -> A -> int) (l_value : t A) : t A :=
  let fix rev_merge (l1 : t A) (l2 : t A) (accu : t A) {struct l1} : t A :=
    match (l1, l2) with
    | ([], l2) => rev_append l2 accu
    | (l1, []) => rev_append l1 accu
    | (Datatypes.cons h1 t1, Datatypes.cons h2 t2) =>
      if RocqOfOCaml.Basics.Stdlib.le (cmp h1 h2) 0 then
        rev_merge t1 l2 (Datatypes.cons h1 accu)
      else
        rev_merge l1 t2 (Datatypes.cons h2 accu)
    end in
  let fix rev_merge_rev (l1 : t A) (l2 : t A) (accu : t A) {struct l1} : t A :=
    match (l1, l2) with
    | ([], l2) => rev_append l2 accu
    | (l1, []) => rev_append l1 accu
    | (Datatypes.cons h1 t1, Datatypes.cons h2 t2) =>
      if RocqOfOCaml.Basics.Stdlib.gt (cmp h1 h2) 0 then
        rev_merge_rev t1 l2 (Datatypes.cons h1 accu)
      else
        rev_merge_rev l1 t2 (Datatypes.cons h2 accu)
    end in
  let sort :=
  fix sort (n_value : int) (l_value : t A) {struct n_value} : t A * t A :=
    match (n_value, l_value) with
    | (2, Datatypes.cons x1 (Datatypes.cons x2 tl)) =>
      let s_value :=
        if RocqOfOCaml.Basics.Stdlib.le (cmp x1 x2) 0 then
          Datatypes.cons x1 (Datatypes.cons x2 nil)
        else
          Datatypes.cons x2 (Datatypes.cons x1 nil) in
      (s_value, tl)
    | (3, Datatypes.cons x1 (Datatypes.cons x2 (Datatypes.cons x3 tl))) =>
      let s_value :=
        if RocqOfOCaml.Basics.Stdlib.le (cmp x1 x2) 0 then
          if RocqOfOCaml.Basics.Stdlib.le (cmp x2 x3) 0 then
            Datatypes.cons x1 (Datatypes.cons x2 (Datatypes.cons x3 nil))
          else
            if RocqOfOCaml.Basics.Stdlib.le (cmp x1 x3) 0 then
              Datatypes.cons x1 (Datatypes.cons x3 (Datatypes.cons x2 nil))
            else
              Datatypes.cons x3 (Datatypes.cons x1 (Datatypes.cons x2 nil))
        else
          if RocqOfOCaml.Basics.Stdlib.le (cmp x1 x3) 0 then
            Datatypes.cons x2 (Datatypes.cons x1 (Datatypes.cons x3 nil))
          else
            if RocqOfOCaml.Basics.Stdlib.le (cmp x2 x3) 0 then
              Datatypes.cons x2 (Datatypes.cons x3 (Datatypes.cons x1 nil))
            else
              Datatypes.cons x3 (Datatypes.cons x2 (Datatypes.cons x1 nil)) in
      (s_value, tl)
    | (n_value, l_value) =>
      let n1 := Z.shiftr n_value 1 in
      let n2 := Z.sub n_value n1 in
      let '(s1, l2) := rev_sort n1 l_value in
      let '(s2, tl) := rev_sort n2 l2 in
      ((rev_merge_rev s1 s2 nil), tl)
    end
  with rev_sort (n_value : int) (l_value : t A) {struct n_value} : t A * t A :=
    match (n_value, l_value) with
    | (2, Datatypes.cons x1 (Datatypes.cons x2 tl)) =>
      let s_value :=
        if RocqOfOCaml.Basics.Stdlib.gt (cmp x1 x2) 0 then
          Datatypes.cons x1 (Datatypes.cons x2 nil)
        else
          Datatypes.cons x2 (Datatypes.cons x1 nil) in
      (s_value, tl)
    | (3, Datatypes.cons x1 (Datatypes.cons x2 (Datatypes.cons x3 tl))) =>
      let s_value :=
        if RocqOfOCaml.Basics.Stdlib.gt (cmp x1 x2) 0 then
          if RocqOfOCaml.Basics.Stdlib.gt (cmp x2 x3) 0 then
            Datatypes.cons x1 (Datatypes.cons x2 (Datatypes.cons x3 nil))
          else
            if RocqOfOCaml.Basics.Stdlib.gt (cmp x1 x3) 0 then
              Datatypes.cons x1 (Datatypes.cons x3 (Datatypes.cons x2 nil))
            else
              Datatypes.cons x3 (Datatypes.cons x1 (Datatypes.cons x2 nil))
        else
          if RocqOfOCaml.Basics.Stdlib.gt (cmp x1 x3) 0 then
            Datatypes.cons x2 (Datatypes.cons x1 (Datatypes.cons x3 nil))
          else
            if RocqOfOCaml.Basics.Stdlib.gt (cmp x2 x3) 0 then
              Datatypes.cons x2 (Datatypes.cons x3 (Datatypes.cons x1 nil))
            else
              Datatypes.cons x3 (Datatypes.cons x2 (Datatypes.cons x1 nil)) in
      (s_value, tl)
    | (n_value, l_value) =>
      let n1 := Z.shiftr n_value 1 in
      let n2 := Z.sub n_value n1 in
      let '(s1, l2) := sort n1 l_value in
      let '(s2, tl) := sort n2 l2 in
      ((rev_merge s1 s2 nil), tl)
    end
  for sort in
  let len := length l_value in
  if RocqOfOCaml.Basics.Stdlib.lt len 2 then
    l_value
  else
    fst (sort len l_value).

